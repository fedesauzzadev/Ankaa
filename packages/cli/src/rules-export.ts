import type { Rule, RulePack, Severity } from "@apigovscan/core";

export type RulesExportFormat = "agents-md" | "prompts-json";

const KEYWORD: Record<Severity, "MUST" | "SHOULD" | "MAY"> = {
  error: "MUST",
  warning: "SHOULD",
  info: "MAY",
};

const SEVERITY_ORDER: Severity[] = ["error", "warning", "info"];

export interface ExportPack {
  id: string;
  version: string;
  rules: Rule[];
}

function sortedRules(pack: ExportPack): Rule[] {
  return [...pack.rules]
    .filter((r) => r.deprecated !== true)
    .sort((a, b) => (a.id < b.id ? -1 : a.id > b.id ? 1 : 0));
}

function fenced(language: string, body: string): string[] {
  return ["```" + language, body.replace(/\n+$/, ""), "```"];
}

function ruleBlock(rule: Rule): string[] {
  const lines = [`### ${rule.id} — ${rule.message}`];
  if (rule.appliesFrom !== undefined && rule.appliesFrom !== "draft") {
    lines.push(`Applies from: ${rule.appliesFrom} endpoints.`);
  }
  if (rule.fix !== undefined) {
    lines.push(`Fix: ${rule.fix}`);
  }
  if (rule.examples?.bad !== undefined) {
    lines.push("Bad example:", ...fenced("yaml", rule.examples.bad));
  }
  if (rule.examples?.good !== undefined) {
    lines.push("Good example:", ...fenced("yaml", rule.examples.good));
  }
  if (rule.source !== undefined) {
    lines.push(
      `Source: ${rule.source.title}${rule.source.section !== undefined ? ` — ${rule.source.section}` : ""} (${rule.source.url})`,
    );
  }
  return lines;
}

/**
 * Render packs as an AGENTS.md block (deterministic: sorted, no timestamps).
 * Severity maps to RFC 2119 keywords: error = MUST, warning = SHOULD, info = MAY.
 */
export function buildAgentsMd(packs: readonly RulePack[]): string {
  const lines = [
    "# API governance rules (generated by `apigovscan rules export` — do not edit by hand)",
    "",
    `Packs: ${[...packs]
      .sort((a, b) => (a.id < b.id ? -1 : a.id > b.id ? 1 : 0))
      .map((p) => `${p.id}@${p.version} (${sortedRules(p).length} rules)`)
      .join(", ")}.`,
    "Severity maps to RFC 2119 keywords: error = MUST, warning = SHOULD, info = MAY.",
    "",
  ];
  for (const severity of SEVERITY_ORDER) {
    const group: Array<{ pack: string; rule: Rule }> = [];
    for (const pack of [...packs].sort((a, b) =>
      a.id < b.id ? -1 : a.id > b.id ? 1 : 0,
    )) {
      for (const rule of sortedRules(pack)) {
        if (rule.severity === severity) group.push({ pack: pack.id, rule });
      }
    }
    if (group.length === 0) continue;
    lines.push(`## ${KEYWORD[severity]}`, "");
    for (const { pack, rule } of group) {
      if (pack !== "elite") lines.push(`Pack: ${pack}.`);
      lines.push(...ruleBlock(rule), "");
    }
  }
  return `${lines.join("\n").replace(/\n+$/, "")}\n`;
}

function rulePrompt(packId: string, rule: Rule): string {
  const lines = [
    `Help me fix an API governance finding for rule ${rule.id} [${rule.severity}, pack ${packId}].`,
    "",
    `Message: ${rule.message}`,
  ];
  if (rule.fix !== undefined) lines.push(`Fix hint: ${rule.fix}`);
  if (rule.examples?.bad !== undefined) lines.push(`Bad example:\n${rule.examples.bad}`);
  if (rule.examples?.good !== undefined) lines.push(`Good example:\n${rule.examples.good}`);
  if (rule.source !== undefined) {
    lines.push(`Source: ${rule.source.title} (${rule.source.url})`);
  }
  lines.push(
    "",
    "Propose the smallest YAML/JSON edit to the spec that resolves a finding of this rule.",
    "Reply with a unified diff plus a one-line explanation.",
  );
  return lines.join("\n");
}

/** Render packs as a JSON remediation-prompt pack (deterministic). */
export function buildPromptsJson(packs: readonly RulePack[]): string {
  const ordered = [...packs].sort((a, b) => (a.id < b.id ? -1 : a.id > b.id ? 1 : 0));
  const prompts: Array<{
    ruleId: string;
    severity: Severity;
    keyword: "MUST" | "SHOULD" | "MAY";
    prompt: string;
  }> = [];
  for (const pack of ordered) {
    for (const rule of sortedRules(pack)) {
      prompts.push({
        ruleId: rule.id,
        severity: rule.severity,
        keyword: KEYWORD[rule.severity],
        prompt: rulePrompt(pack.id, rule),
      });
    }
  }
  return (
    `${JSON.stringify(
      {
        tool: "apigovscan",
        packs: ordered.map((p) => ({ id: p.id, version: p.version, count: sortedRules(p).length })),
        prompts,
      },
      null,
      2,
    )}\n`
  );
}
