export type LineReader = () => Promise<string>;

export interface GuidedIO {
  stdout: (text: string) => void;
  stderr: (text: string) => void;
  env: Record<string, string | undefined>;
  cwd: string;
  readLine: LineReader;
}

export interface CiWorkflowOptions {
  path: string;
  failOn: string;
  mode: "analyze" | "review";
  reviewRef?: string;
}

const FAIL_ON_CHOICES = ["error", "warning", "info", "never"] as const;
type FailOn = (typeof FAIL_ON_CHOICES)[number];

function normalizeLabel(absPath: string, cwd: string): string {
  const rel = absPath.startsWith(cwd)
    ? absPath.slice(cwd.length).replace(/^[\\/]+/, "")
    : absPath;
  return rel.split("\\").join("/");
}

export function buildCiWorkflow(opts: CiWorkflowOptions): string {
  const lines = [
    "# Generated by `apigovscan guided` — review before committing.",
    "# ApiGovScan never changes branch protection or platform settings;",
    "# making this check required is a repository setting you control.",
    "name: API governance",
    "on:",
    "  pull_request:",
    "    branches: [main]",
    "  push:",
    "    branches: [main]",
    "jobs:",
    "  apigovscan:",
    "    name: ApiGovScan",
    "    runs-on: ubuntu-latest",
    "    permissions:",
    "      contents: read",
    "    steps:",
    "      - uses: actions/checkout@v4",
    "        with:",
    "          fetch-depth: 0",
    "      - name: ApiGovScan",
    "        id: apigovscan",
    "        uses: owner/repo@v1 # TODO: point at your ApiGovScan action ref",
    "        with:",
    `          path: ${opts.path}`,
    `          fail-on: ${opts.failOn}`,
  ];
  if (opts.mode === "review") {
    lines.push(`          review-ref: ${opts.reviewRef ?? "main"}`);
  }
  lines.push("");
  return lines.join("\n");
}

export function guidedHelp(): string {
  return [
    "usage: apigovscan guided",
    "",
    "Terminal assistant for ApiGovScan: pick an action from a menu, validate",
    "inputs, confirm before anything runs or gets written, and cancel anytime.",
    "Runs the same use cases as the CLI; no TTY-specific rendering required.",
  ].join("\n");
}

class ClosedInputError extends Error {}

export function queueLineReader(lines: readonly string[]): LineReader {
  let index = 0;
  return async () => {
    if (index >= lines.length) throw new ClosedInputError();
    const line = lines[index]!;
    index += 1;
    return line;
  };
}

export function createStdinLineReader(): { readLine: LineReader; close: () => void } {
  const rl = createInterface({ input: process.stdin });
  const lines: string[] = [];
  const waiters: Array<() => void> = [];
  let eof = false;
  rl.on("line", (line: string) => {
    lines.push(line);
    waiters.splice(0).forEach((wake) => wake());
  });
  rl.on("close", () => {
    eof = true;
    waiters.splice(0).forEach((wake) => wake());
  });
  return {
    readLine: async () => {
      for (;;) {
        if (lines.length > 0) return lines.shift()!;
        if (eof) throw new ClosedInputError();
        await new Promise<void>((resolvePromise) => waiters.push(resolvePromise));
      }
    },
    close: () => rl.close(),
  };
}

export async function runGuided(io: GuidedIO): Promise<number> {
  const ask = async (prompt: string): Promise<string> => {
    io.stdout(`${prompt} `);
    return io.readLine();
  };

  for (;;) {
    io.stdout("\nApiGovScan guided — available actions\n\n");
    io.stdout(`1. ${ANALYZE_OPERATION.title}\n   ${ANALYZE_OPERATION.description}\n`);
    io.stdout("2. Prepare CI configuration\n   Preview a GitHub Actions workflow and write it only after confirmation.\n");
    io.stdout("3. Exit\n\n");

    let choice: string;
    try {
      choice = (await ask("Choose an option [1-3]:")).trim();
    } catch (err) {
      if (err instanceof ClosedInputError) return 0;
      throw err;
    }

    if (choice === "3" || choice === "" || choice === "q" || choice === "quit") {
      io.stdout("Bye.\n");
      return 0;
    }
    if (choice === "1") {
      const code = await analyzeFlow(io, ask);
      if (code !== null) return code;
      continue;
    }
    if (choice === "2") {
      const code = await ciFlow(io, ask);
      if (code !== null) return code;
      continue;
    }
    io.stdout("Invalid option; enter 1, 2 or 3.\n");
  }
}

async function askPath(io: GuidedIO, ask: (p: string) => Promise<string>): Promise<string | null> {
  for (;;) {
    let typed: string;
    try {
      typed = (await ask("Spec file or directory (empty to cancel):")).trim();
    } catch (err) {
      if (err instanceof ClosedInputError) return null;
      throw err;
    }
    if (typed === "") {
      io.stdout("Cancelled — nothing was run.\n");
      return null;
    }
    if (typed === "-") {
      io.stdout("stdin is not supported here; pass a file or directory.\n");
      continue;
    }
    const abs = isAbsolute(typed) ? typed : resolve(io.cwd, typed);
    if (!existsSync(abs)) {
      io.stdout(`input not found: ${typed}\n`);
      continue;
    }
    const stat = statSync(abs);
    if (!stat.isFile() && !stat.isDirectory()) {
      io.stdout(`not a file or directory: ${typed}\n`);
      continue;
    }
    return typed;
  }
}

async function askFailOn(io: GuidedIO, ask: (p: string) => Promise<string>): Promise<FailOn> {
  for (;;) {
    let typed: string;
    try {
      typed = (await ask("Fail threshold error|warning|info|never [error]:")).trim();
    } catch (err) {
      if (err instanceof ClosedInputError) return "error";
      throw err;
    }
    if (typed === "") return "error";
    if ((FAIL_ON_CHOICES as readonly string[]).includes(typed)) return typed as FailOn;
    io.stdout("Invalid threshold; use error, warning, info or never.\n");
  }
}

async function confirm(io: GuidedIO, ask: (p: string) => Promise<string>): Promise<boolean> {
  let typed: string;
  try {
    typed = (await ask("Continue? [y/N]:")).trim().toLowerCase();
  } catch (err) {
    if (err instanceof ClosedInputError) return false;
    throw err;
  }
  return typed === "y" || typed === "yes";
}

async function analyzeFlow(io: GuidedIO, ask: (p: string) => Promise<string>): Promise<number | null> {
  const typedPath = await askPath(io, ask);
  if (typedPath === null) return null;
  const failOn = await askFailOn(io, ask);
  io.stdout(`\nWill analyze "${typedPath}" with fail-on ${failOn}. No files will be written.\n`);
  if (!(await confirm(io, ask))) {
    io.stdout("Cancelled — nothing was run.\n");
    return null;
  }

  const abs = isAbsolute(typedPath) ? typedPath : resolve(io.cwd, typedPath);
  const configResult = loadConfig(io.cwd, undefined);
  if (!configResult.ok) {
    io.stderr(`error: ${configResult.error}\n`);
    return 2;
  }
  const prepared = prepareAnalysis(io.cwd, configResult.config, {
    rulesFiles: [],
    baselineMode: configResult.config.baseline?.enabled === true ? "read" : "off",
  });
  if (!prepared.ok) {
    io.stderr(`error: ${prepared.error}\n`);
    return 2;
  }
  const setup = prepared.setup;

  let inputs: string[];
  if (statSync(abs).isDirectory()) {
    const discovered = discoverSpecs(abs);
    if (!discovered.ok) {
      io.stderr(`error: ${discovered.error}\n`);
      return 2;
    }
    inputs = discovered.paths.map((p) => resolve(abs, p));
    if (inputs.length === 0) {
      io.stderr(`error: no specs found in ${typedPath}\n`);
      return 2;
    }
  } else {
    inputs = [abs];
  }

  const outcome = await analyzeUseCase(
    {
      loader: createFsSpecLoader(),
      packs: createFsPackRepository(io.cwd),
      sink: { async write() {} },
    },
    {
      inputs,
      labelFor: (p) => normalizeLabel(p, io.cwd),
      failOn,
      customRules: setup.customRules as Rule[] | undefined,
      disabledRuleIds: setup.disabledRuleIds,
      severityOverrides: setup.severityOverrides,
      skillsSuppressions: setup.skillsSuppressions,
      baselineFingerprints: setup.baselineFingerprints,
      toolVersion: packageVersion(),
    },
  );
  if (!outcome.ok) {
    io.stderr(`error: ${outcome.error}\n`);
    return 2;
  }
  io.stdout("\n");
  io.stdout(formatConsole(outcome.report, { color: false }));
  io.stdout(`reportHash ${outcome.report.reportHash}\n`);
  return outcome.exitCode;
}

async function ciFlow(io: GuidedIO, ask: (p: string) => Promise<string>): Promise<number | null> {
  let mode: "analyze" | "review" = "analyze";
  let reviewRef: string | undefined;
  let typed: string;
  try {
    typed = (await ask("Mode analyze|review [analyze]:")).trim().toLowerCase();
  } catch (err) {
    if (err instanceof ClosedInputError) return null;
    throw err;
  }
  if (typed === "") typed = "analyze";
  if (typed === "review") {
    mode = "review";
    try {
      reviewRef = (await ask("Baseline ref for review [main]:")).trim() || "main";
    } catch (err) {
      if (err instanceof ClosedInputError) return null;
      throw err;
    }
  } else if (typed !== "analyze") {
    io.stdout("Invalid mode; choose analyze or review.\n");
    return null;
  }

  const specPath = await askPath(io, ask);
  if (specPath === null) return null;
  const failOn = await askFailOn(io, ask);
  let dest: string;
  try {
    dest = (await ask("Destination file [.github/workflows/apigovscan.yml]:")).trim();
  } catch (err) {
    if (err instanceof ClosedInputError) return null;
    throw err;
  }
  if (dest === "") dest = join(".github", "workflows", "apigovscan.yml");
  const destAbs = isAbsolute(dest) ? dest : resolve(io.cwd, dest);

  const content = buildCiWorkflow({ path: specPath, failOn, mode, reviewRef });
  io.stdout(`\n--- preview of ${dest} ---\n${content}--- end of preview ---\n`);
  io.stdout(
    "This writes one file only. ApiGovScan does not enable branch protection or change platform settings.\n",
  );
  if (!(await confirm(io, ask))) {
    io.stdout("Cancelled — nothing was written.\n");
    return null;
  }
  if (existsSync(destAbs)) {
    io.stdout(`destination already exists: ${dest}\n`);
    if (!(await confirm(io, ask))) {
      io.stdout("Cancelled — existing file kept.\n");
      return null;
    }
  }
  try {
    mkdirSync(dirname(destAbs), { recursive: true });
    writeFileSync(destAbs, content, "utf8");
  } catch (err) {
    io.stderr(`error: cannot write ${dest}: ${err instanceof Error ? err.message : String(err)}\n`);
    return 2;
  }
  io.stdout(`written ${dest}\n`);
  return null;
}
