export type LineReader = () => Promise<string>;

export interface GuidedIO {
  stdout: (text: string) => void;
  stderr: (text: string) => void;
  env: Record<string, string | undefined>;
  cwd: string;
  readLine: LineReader;
}

export interface CiWorkflowOptions {
  path: string;
  failOn: string;
  mode: "analyze" | "review";
  reviewRef?: string;
}

const FAIL_ON_CHOICES = ["error", "warning", "info", "never"] as const;
type FailOn = (typeof FAIL_ON_CHOICES)[number];

function normalizeLabel(absPath: string, cwd: string): string {
  const rel = absPath.startsWith(cwd)
    ? absPath.slice(cwd.length).replace(/^[\\/]+/, "")
    : absPath;
  return rel.split("\\").join("/");
}

export function buildCiWorkflow(opts: CiWorkflowOptions): string {
  const lines = [
    "# Generated by `ankaa guided` — review before committing.",
    "# Ankaa never changes branch protection or platform settings;",
    "# making this check required is a repository setting you control.",
    "name: API governance",
    "on:",
    "  pull_request:",
    "    branches: [main]",
    "  push:",
    "    branches: [main]",
    "jobs:",
    "  ankaa:",
    "    name: Ankaa",
    "    runs-on: ubuntu-latest",
    "    permissions:",
    "      contents: read",
    "    steps:",
    "      - uses: actions/checkout@v4",
    "        with:",
    "          fetch-depth: 0",
    "      - name: Ankaa",
    "        id: ankaa",
    "        uses: owner/repo@v1 # TODO: point at your Ankaa action ref",
    "        with:",
    `          path: ${opts.path}`,
    `          fail-on: ${opts.failOn}`,
  ];
  if (opts.mode === "review") {
    lines.push(`          review-ref: ${opts.reviewRef ?? "main"}`);
  }
  lines.push("");
  return lines.join("\n");
}

